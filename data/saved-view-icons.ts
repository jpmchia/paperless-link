const ICONS_BY_ID = new Map(SAVED_VIEW_ICONS.map((item) => [item.id, item]))

export function normalizeSavedViewIcon(icon?: string | null) {
  return icon && ICONS_BY_ID.has(icon) ? icon : DEFAULT_SAVED_VIEW_ICON
}

export function getSavedViewIcon(icon?: string | null): LucideIcon {
  return ICONS_BY_ID.get(normalizeSavedViewIcon(icon))!.icon
}
